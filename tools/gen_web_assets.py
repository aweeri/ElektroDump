#!/usr/bin/env python3
"""Embed web/ assets into a C++ include (spec M9 section 4.3).

Produces build/gen/web_assets.inc containing a kWebAssets[] table of
{ path, mime, data, size } entries, mirroring the default_config.inc pattern.

The output is deterministic: files are sorted by relative path and no
timestamps are emitted, so unchanged inputs produce byte-identical output.

Usage:
    gen_web_assets.py <web_dir> <out_file>
"""
import os
import sys

MIME = {
    ".html": "text/html; charset=utf-8",
    ".htm": "text/html; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".js": "application/javascript; charset=utf-8",
    ".json": "application/json; charset=utf-8",
    ".map": "application/json; charset=utf-8",
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".ico": "image/x-icon",
    ".webmanifest": "application/manifest+json; charset=utf-8",
    ".txt": "text/plain; charset=utf-8",
}

SKIP_NAMES = {"README.md", ".gitkeep", ".DS_Store"}


def mime_for(path):
    ext = os.path.splitext(path)[1].lower()
    return MIME.get(ext, "application/octet-stream")


def collect(web_dir):
    entries = []
    for root, dirs, files in os.walk(web_dir):
        dirs.sort()
        for name in sorted(files):
            if name in SKIP_NAMES or name.startswith("."):
                continue
            full = os.path.join(root, name)
            rel = os.path.relpath(full, web_dir).replace(os.sep, "/")
            entries.append((rel, full))
    entries.sort(key=lambda entry: entry[0])
    return entries


def raw_delimiter(data):
    delim = "EDWEBASSET"
    while (")" + delim + '"').encode("ascii") in data:
        delim += "X"
    return delim


def main():
    if len(sys.argv) != 3:
        sys.stderr.write("usage: gen_web_assets.py <web_dir> <out_file>\n")
        return 2

    web_dir, out_file = sys.argv[1], sys.argv[2]
    if not os.path.isdir(web_dir):
        sys.stderr.write(
            "error: web asset directory not found: %s\n" % web_dir)
        return 1

    entries = collect(web_dir)
    if not entries:
        sys.stderr.write("error: no web assets found under %s\n" % web_dir)
        return 1

    out_dir = os.path.dirname(out_file)
    if out_dir and not os.path.isdir(out_dir):
        os.makedirs(out_dir)

    lines = []
    lines.append("// Generated by tools/gen_web_assets.py -- do not edit.")
    lines.append("// Embedded web assets (spec M9 section 4.3).")
    lines.append("static const WebAsset kWebAssets[] = {")
    for rel, full in entries:
        with open(full, "rb") as handle:
            data = handle.read()
        if b"\x00" in data:
            sys.stderr.write(
                "error: NUL byte in text asset %s (binary assets unsupported)\n"
                % rel)
            return 1
        text = data.decode("utf-8")
        delim = raw_delimiter(data)
        lines.append('    {"%s", "%s",' % (rel, mime_for(rel)))
        lines.append('     R"%s(%s)%s", %d},' % (delim, text, delim, len(data)))
    lines.append("};")
    lines.append("static const std::size_t kWebAssetCount = %d;" % len(entries))
    lines.append("")

    with open(out_file, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines))

    print("gen_web_assets: embedded %d asset(s) -> %s"
          % (len(entries), out_file))
    return 0


if __name__ == "__main__":
    sys.exit(main())
